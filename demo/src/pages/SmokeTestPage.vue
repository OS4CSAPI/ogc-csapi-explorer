/** Unique keyword embedded in all smoke-test resources so they can be found
 *  via the Explorer page's free-text search (q filter).  Search for this
 *  exact string to see only smoke-test leftovers. */
const SMOKE_TAG = 'csapi-smoke-test-resource'

function makePayload(type: string, phase: 'create' | 'update'): any {
  const coords = COORDS[type]
  const c = coords ? coords[phase] : undefined
  const geom = c ? { type: 'Point', coordinates: c } : null

  const uid = phase === 'create'
    ? `urn:csapi-explorer:smoke-test:${type}:${Date.now()}`
    : createdUids[type]  // Reuse original UID on update — OSH requires it
  const name = phase === 'create'
    ? `[${SMOKE_TAG}] Smoke Test ${type}`
    : `[${SMOKE_TAG}] Smoke Test ${type} (updated)`

  const featureTypes: Record<string, string> = {
    systems: 'http://www.w3.org/ns/sosa/Platform',
    procedures: 'http://www.w3.org/ns/sosa/Procedure',
    deployments: 'http://www.w3.org/ns/sosa/Deployment',
    samplingFeatures: 'http://www.w3.org/ns/sosa/Sample',
  }

  if (['systems', 'procedures', 'deployments', 'samplingFeatures'].includes(type)) {
    return {
      type: 'Feature',
      properties: {
        featureType: featureTypes[type],
        name,
        uid,
        description: `Auto-generated by CRUD smoke test (${phase}). Tag: ${SMOKE_TAG}`,
      },
      geometry: geom,
    }
  }

  // Subsystems are systems created under a parent system
  if (type === 'subsystems') {
    return {
      type: 'Feature',
      properties: {
        featureType: 'http://www.w3.org/ns/sosa/Sensor',
        name: phase === 'create'
          ? `[${SMOKE_TAG}] Smoke Test Subsystem`
          : `[${SMOKE_TAG}] Smoke Test Subsystem (updated)`,
        uid: phase === 'create'
          ? `urn:csapi-explorer:smoke-test:subsystem:${Date.now()}`
          : createdUids['subsystems'],
        description: `Subsystem sensor created under parent system. Tag: ${SMOKE_TAG}`,
      },
      geometry: geom,
    }
  }

  // Subdeployments are deployments created under a parent deployment
  if (type === 'subdeployments') {
    return {
      type: 'Feature',
      properties: {
        featureType: 'http://www.w3.org/ns/sosa/Deployment',
        name: phase === 'create'
          ? `[${SMOKE_TAG}] Smoke Test Subdeployment`
          : `[${SMOKE_TAG}] Smoke Test Subdeployment (updated)`,
        uid: phase === 'create'
          ? `urn:csapi-explorer:smoke-test:subdeployment:${Date.now()}`
          : createdUids['subdeployments'],
        description: `Subdeployment created under parent deployment. Tag: ${SMOKE_TAG}`,
      },
      geometry: geom,
    }
  }

  if (type === 'datastreams') {
    return {
      name,
      outputName: 'smoke-test-output',
      schema: {
        obsFormat: 'application/swe+json',
        recordSchema: {
          type: 'DataRecord',
          label: 'Smoke Test Record',
          fields: [
            { type: 'Time', label: 'Timestamp', name: 'timestamp', definition: 'http://www.opengis.net/def/property/OGC/0/SamplingTime', uom: { href: 'http://www.opengis.net/def/uom/ISO-8601/0/Gregorian' } },
            { type: 'Quantity', label: 'Temperature', name: 'temp', uom: { code: 'Cel' } },
            { type: 'DataRecord', label: 'Location', name: 'location', fields: [
              { type: 'Quantity', label: 'Latitude', name: 'lat', uom: { code: 'deg' } },
              { type: 'Quantity', label: 'Longitude', name: 'lon', uom: { code: 'deg' } },
            ]},
          ]
        }
      }
    }
  }

  if (type === 'observations') {
    const obsCoords = COORDS['observations']?.[phase]
    return {
      phenomenonTime: new Date().toISOString(),
      resultTime: new Date().toISOString(),
      result: {
        temp: phase === 'create' ? 22.5 : 25.0,
        location: obsCoords ? { lat: obsCoords[1], lon: obsCoords[0] } : undefined,
      },
    }
  }

  if (type === 'controlStreams') {
    // CREATE: include full schema; UPDATE: omit schema — OSH returns 500 on
    // PUT when the schema block is present (server bug in control stream update handler)
    if (phase === 'create') {
      return {
        name,
        inputName: 'smoke-test-input',
        schema: {
          paramsSchema: {
            type: 'DataRecord',
            label: 'Smoke Test Command',
            fields: [
              { type: 'Time', label: 'Timestamp', name: 'timestamp', definition: 'http://www.opengis.net/def/property/OGC/0/SamplingTime', uom: { href: 'http://www.opengis.net/def/uom/ISO-8601/0/Gregorian' } },
              { type: 'Boolean', label: 'Active', name: 'active' },
            ]
          }
        }
      }
    }
    return {
      name,
      inputName: 'smoke-test-input',
    }
  }

  if (type === 'commands') {
    return {
      issueTime: new Date().toISOString(),
      parameters: { active: phase === 'create' },
    }
  }

  return { name }
}

// ─── Step Building ───────────────────────────────────────

const PART1_TYPES = ['systems', 'procedures', 'deployments', 'samplingFeatures']
const NESTED_HIERARCHY_TYPES = ['subsystems', 'subdeployments']  // Nested under Part 1 parents
const PART2_PARENT_TYPES = ['datastreams', 'controlStreams']   // Need parent system alive
const PART2_CHILD_TYPES_CRD = ['observations']                    // Immutable but persisted — CREATE/READ/DELETE
const PART2_CHILD_TYPES_CREATE_ONLY = ['commands']                 // Async dispatch (202) — CREATE only, no persisted resource
const CRUV_OPS: OpType[] = ['CREATE', 'READ', 'UPDATE', 'VERIFY']  // No DELETE — children need parents alive
const CRUD_OPS: OpType[] = ['CREATE', 'READ', 'UPDATE', 'VERIFY', 'DELETE']
const CRD_OPS: OpType[] = ['CREATE', 'READ', 'DELETE']  // Observations — immutable, no UPDATE
const CREATE_ONLY_OPS: OpType[] = ['CREATE']  // Commands — async dispatch, 202 with no persisted ID

/** Maps virtual nested types to their actual resource type (for content-type, detail/update/delete URLs) */
const NESTED_ACTUAL_TYPE: Record<string, string> = {
  subsystems: 'systems',
  subdeployments: 'deployments',
}

/** Maps virtual nested types to the parent type they nest under */
const NESTED_PARENT_TYPE: Record<string, string> = {
  subsystems: 'systems',
  subdeployments: 'deployments',
}

/** Human-readable labels for virtual nested types */
const NESTED_LABELS: Record<string, string> = {
  subsystems: 'Subsystem',
  subdeployments: 'Subdeployment',
}

function buildSteps(): Step[] {
  const steps: Step[] = []
  let id = 1
  // Phase 1: Part 1 CRUV (keep Part 1 resources alive for Part 2 parents)
  for (const key of PART1_TYPES) {
    const info = RESOURCE_TYPES.find((r) => r.key === key)!
    for (const op of CRUV_OPS) {
      steps.push({ id: id++, resourceType: key, resourceLabel: info.label, op, status: 'pending' })
    }
  }
  // Phase 1b: Nested hierarchy CRUV (subsystems under systems, subdeployments under deployments)
  for (const key of NESTED_HIERARCHY_TYPES) {
    const label = NESTED_LABELS[key]
    for (const op of CRUV_OPS) {
      steps.push({ id: id++, resourceType: key, resourceLabel: label, op, status: 'pending' })
    }
  }
  // Phase 1c: Nested hierarchy DELETE (before parents are deleted)
  for (const key of NESTED_HIERARCHY_TYPES) {
    const label = NESTED_LABELS[key]
    steps.push({ id: id++, resourceType: key, resourceLabel: label, op: 'DELETE', status: 'pending' })
  }
  // Phase 2a: Part 2 parent CRUV (keep datastreams/controlStreams alive for observations/commands)
  for (const key of PART2_PARENT_TYPES) {
    const info = RESOURCE_TYPES.find((r) => r.key === key)!
    for (const op of CRUV_OPS) {
      steps.push({ id: id++, resourceType: key, resourceLabel: info.label, op, status: 'pending' })
    }
  }
  // Phase 2b: Part 2 child CRD (observations — immutable, no UPDATE)
  for (const key of PART2_CHILD_TYPES_CRD) {
    const info = RESOURCE_TYPES.find((r) => r.key === key)!
    for (const op of CRD_OPS) {
      steps.push({ id: id++, resourceType: key, resourceLabel: info.label, op, status: 'pending' })
    }
  }
  // Phase 2b-2: Commands — async dispatch only (OSH returns 202, no persisted resource)
  for (const key of PART2_CHILD_TYPES_CREATE_ONLY) {
    const info = RESOURCE_TYPES.find((r) => r.key === key)!
    for (const op of CREATE_ONLY_OPS) {
      steps.push({ id: id++, resourceType: key, resourceLabel: info.label, op, status: 'pending' })
    }
  }
  // Phase 2c: Part 2 parent DELETE (cleanup datastreams/controlStreams after children are done)
  for (const key of PART2_PARENT_TYPES) {
    const info = RESOURCE_TYPES.find((r) => r.key === key)!
    steps.push({ id: id++, resourceType: key, resourceLabel: info.label, op: 'DELETE', status: 'pending' })
  }
  // Phase 3: Part 1 DELETE (cleanup systems, procedures, etc.)
  for (const key of PART1_TYPES) {
    const info = RESOURCE_TYPES.find((r) => r.key === key)!
    steps.push({ id: id++, resourceType: key, resourceLabel: info.label, op: 'DELETE', status: 'pending' })
  }
  return steps
}

// ─── Reactive State ──────────────────────────────────────

const steps = ref<Step[]>(buildSteps())
