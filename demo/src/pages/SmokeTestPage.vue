function addMarker(resourceType: string, coords: [number, number], featureId: string, phase: 'create' | 'update') {
  const existing = vectorSource.getFeatureById(featureId)
  if (existing) vectorSource.removeFeature(existing)

  if (phase === 'update') {
    const oldCoords = COORDS[resourceType]?.create
    if (oldCoords) {
      const ghostId = featureId + '-ghost'
      const existingGhost = vectorSource.getFeatureById(ghostId)
      if (existingGhost) vectorSource.removeFeature(existingGhost)
      const ghost = new OlFeature({ geometry: new OlPoint(fromLonLat(oldCoords)) })
      ghost.setId(ghostId)
      ghost.setStyle(markerStyle(resourceType, 'ghost'))
      vectorSource.addFeature(ghost)
    }
  }

  const feature = new OlFeature({ geometry: new OlPoint(fromLonLat(coords)) })
  feature.setId(featureId)
  feature.setStyle(markerStyle(resourceType, phase))
  vectorSource.addFeature(feature)

  map?.getView().animate({ center: fromLonLat(coords), duration: 600 })
}

function removeMarker(featureId: string) {
  const f = vectorSource.getFeatureById(featureId)
  if (f) vectorSource.removeFeature(f)
  const g = vectorSource.getFeatureById(featureId + '-ghost')
  if (g) vectorSource.removeFeature(g)
}

