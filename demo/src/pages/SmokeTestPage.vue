// ─── Preview: prepare what the step WILL do ──────────────

function prepareStepPreview(step: Step) {
  const actualType = NESTED_ACTUAL_TYPE[step.resourceType] || step.resourceType
  const contentType = getContentType(actualType)

  switch (step.op) {
    case 'CREATE': {
      let parentId: string | undefined
      if (step.resourceType === 'datastreams' || step.resourceType === 'controlStreams') {
        parentId = createdIds['systems']
      }
      if (step.resourceType === 'observations') parentId = createdIds['datastreams']
      if (step.resourceType === 'commands') parentId = createdIds['controlStreams']
      // Nested hierarchy types
      if (NESTED_PARENT_TYPE[step.resourceType]) {
        parentId = createdIds[NESTED_PARENT_TYPE[step.resourceType]]
      }

      const url = getCreateUrl(step.resourceType, parentId)
      const payload = makePayload(step.resourceType, 'create')
      step.request = {
        method: 'POST',
        url,
        headers: { 'Content-Type': contentType },
        body: JSON.stringify(payload, null, 2),
      }
      break
    }
    case 'READ':
    case 'VERIFY': {
      const id = createdIds[step.resourceType]
      if (id) {
        step.request = {
          method: 'GET',
          url: getDetailUrl(actualType, id),
          headers: { 'Accept': contentType },
        }
      }
      break
    }
    case 'UPDATE': {
      const id = createdIds[step.resourceType]
      if (id) {
        const payload = makePayload(step.resourceType, 'update')
        step.request = {
          method: 'PUT',
          url: getUpdateUrl(actualType, id),
          headers: { 'Content-Type': contentType, 'Accept': contentType },
          body: JSON.stringify(payload, null, 2),
        }
      }
      break
    }
    case 'DELETE': {
      const id = createdIds[step.resourceType]
      if (id) {
        step.request = {
          method: 'DELETE',
          url: getDeleteUrl(actualType, id),
          headers: {},
        }
      }
      break
    }
  }
}

// ─── Retry Helper ────────────────────────────────────────

/** Retry an apiFetch call on transient server errors (500, 502, 503, 504). */
async function apiFetchWithRetry(
  url: string,
  options: RequestInit = {},
  retries = 1,
  delayMs = 800
): Promise<any> {
  const resp = await apiFetch(url, options)
  if (!resp.ok && retries > 0 && [500, 502, 503, 504].includes(resp.status)) {
    await new Promise(r => setTimeout(r, delayMs))
    return apiFetchWithRetry(url, options, retries - 1, delayMs * 1.5)
  }
  return resp
}

// ─── Pre-Clean: purge orphaned smoke-test resources ──────

const preCleanMessage = ref('')
const preCleanRunning = ref(false)

async function preClean() {
  preCleanRunning.value = true
  preCleanMessage.value = 'Scanning for orphaned smoke-test resources…'
  const types = ['commands', 'controlstreams', 'observations', 'datastreams',
                 'subsystems', 'subdeployments', 'samplingFeatures',
                 'deployments', 'procedures', 'systems']
  let totalDeleted = 0
  for (const type of types) {
    try {
      const listUrl = `/${type === 'subsystems' ? 'systems' : (type === 'subdeployments' ? 'deployments' : type)}?q=${SMOKE_TAG}&limit=50`
      const resp = await apiFetch(listUrl, { method: 'GET', headers: { 'Accept': 'application/json' } })
      if (!resp.ok || !resp.data?.items) continue
      for (const item of resp.data.items) {
        const id = item.id || item.properties?.id
        if (!id) continue
        const actual = type === 'subsystems' ? 'systems' : (type === 'subdeployments' ? 'deployments' : type)
        try {
          await apiFetch(`/${actual}/${id}`, { method: 'DELETE' })
          totalDeleted++
        } catch { /* best effort */ }
      }
    } catch { /* best effort */ }
  }
  preCleanMessage.value = totalDeleted > 0
    ? `Purged ${totalDeleted} orphaned resource(s)`
    : 'Server is clean — no orphans found'
  preCleanRunning.value = false
  setTimeout(() => { preCleanMessage.value = '' }, 4000)
}

// ─── Warm Up: ping server to ensure JVM / cold-start is past ──

const warmUpMessage = ref('')
const warmUpRunning = ref(false)
const warmUpReady = ref(false)

async function warmUp() {
  warmUpRunning.value = true
  warmUpReady.value = false
  warmUpMessage.value = 'Warming up server…'

  const MAX_PINGS = 6
  const READY_THRESHOLD_MS = 1500  // sub-1.5s = warm
  let consecutiveFast = 0

  for (let i = 0; i < MAX_PINGS; i++) {
    const start = performance.now()
    try {
      const resp = await apiFetch('/systems?limit=1', { method: 'GET', headers: { Accept: 'application/json' } })
      const elapsed = Math.round(performance.now() - start)
      if (resp.ok && elapsed < READY_THRESHOLD_MS) {
        consecutiveFast++
        warmUpMessage.value = `Ping ${i + 1}/${MAX_PINGS}: ${elapsed}ms ✓`
        if (consecutiveFast >= 2) {
          warmUpMessage.value = `Server ready — ${elapsed}ms response`
          warmUpReady.value = true
          warmUpRunning.value = false
          setTimeout(() => { warmUpMessage.value = '' }, 5000)
          return
        }
      } else {
        consecutiveFast = 0
        warmUpMessage.value = resp.ok
          ? `Ping ${i + 1}/${MAX_PINGS}: ${elapsed}ms (warming…)`
          : `Ping ${i + 1}/${MAX_PINGS}: ${resp.status} (retrying…)`
      }
    } catch {
      consecutiveFast = 0
      warmUpMessage.value = `Ping ${i + 1}/${MAX_PINGS}: error (retrying…)`
    }
    // Brief pause between pings
    await new Promise(r => setTimeout(r, 600))
  }

  // Finished all pings without consecutive fast responses
  warmUpMessage.value = 'Warm-up complete — server may still be sluggish'
  warmUpReady.value = true
  warmUpRunning.value = false
  setTimeout(() => { warmUpMessage.value = '' }, 5000)
}

// ─── Step Execution ──────────────────────────────────────

async function executeCurrentStep() {
  const step = activeStep.value
  if (!step || step.status !== 'active') return

  step.status = 'running'
  const start = performance.now()

  const actualType = NESTED_ACTUAL_TYPE[step.resourceType] || step.resourceType
  const contentType = getContentType(actualType)

  try {
    switch (step.op) {
      case 'CREATE': {
        let parentId: string | undefined
        if (step.resourceType === 'datastreams' || step.resourceType === 'controlStreams') {
          parentId = createdIds['systems']
          if (!parentId) { markSkipped(step, 'No parent system created — skipping', start); return }
        }
        if (step.resourceType === 'observations') {
          parentId = createdIds['datastreams']
          if (!parentId) { markSkipped(step, 'No parent datastream created — skipping', start); return }
        }
        if (step.resourceType === 'commands') {
          parentId = createdIds['controlStreams']
          if (!parentId) { markSkipped(step, 'No parent control stream created — skipping', start); return }
        }
        // Nested hierarchy types
        if (NESTED_PARENT_TYPE[step.resourceType]) {
          parentId = createdIds[NESTED_PARENT_TYPE[step.resourceType]]
          if (!parentId) { markSkipped(step, `No parent ${NESTED_PARENT_TYPE[step.resourceType]} created — skipping`, start); return }
        }

        const url = getCreateUrl(step.resourceType, parentId)
        const payload = makePayload(step.resourceType, 'create')
        const bodyStr = JSON.stringify(payload, null, 2)

        // Only send Content-Type, NOT Accept — OSH may reject Accept: application/geo+json
        // apiFetch defaults Accept to application/json which works fine
        step.request = {
          method: 'POST', url,
          headers: { 'Content-Type': contentType },
          body: bodyStr,
        }
        step.before = null

        const resp = await apiFetchWithRetry(url, {
          method: 'POST',
          headers: { 'Content-Type': contentType },
          body: bodyStr,
        })

        setResponse(step, resp)

        if (!resp.ok) {
          // Command CREATE: OSH rejects commands for API-created systems with no
          // connected driver ("Receiving system is disabled").  The JSON was parsed
          // correctly — this is a server-side limitation, not a payload error.
          const errText = resp.error || resp.statusText || ''
          if (step.resourceType === 'commands' && /rejected|disabled|not supported|no receiver|no handler|not available/i.test(errText)) {
            markSkipped(step, 'Command parsed OK — rejected by server (no connected driver)', start)
            return
          }
          markFail(step, resp.error || `${resp.status} ${resp.statusText}`, start)
          return
        }

        // Extract ID from Location header
        const location = resp.headers['location'] || ''
        const id = location.split('/').pop() || ''
        if (id) createdIds[step.resourceType] = id

        // Store the UID so UPDATE can include it (OSH requires it)
        const payload2 = JSON.parse(bodyStr)
        if (payload2?.properties?.uid) createdUids[step.resourceType] = payload2.properties.uid

        step.after = resp.data || { _smokeTest: true, id, location }
        step.status = 'success'

        // Map
        const coords = COORDS[step.resourceType]?.create
        if (coords && id) {
          step.coords = coords
          addMarker(step.resourceType, coords, `smoke-${step.resourceType}`, 'create')
        }
        break
      }

      case 'READ': {
        const id = createdIds[step.resourceType]
        if (!id) { markSkipped(step, 'No ID from CREATE — skipping', start); return }

        const url = getDetailUrl(actualType, id)
        step.request = { method: 'GET', url, headers: { 'Accept': contentType } }

        const resp = await apiFetchWithRetry(url, { method: 'GET', headers: { 'Accept': contentType } })
        setResponse(step, resp)

        if (!resp.ok) {
          markFail(step, resp.error || `${resp.status} ${resp.statusText}`, start)
        } else {
          step.before = null
          step.after = resp.data
          step.status = 'success'
          const coords = COORDS[step.resourceType]?.create
          if (coords) step.coords = coords
        }
        break
      }

      case 'UPDATE': {
        const id = createdIds[step.resourceType]
        if (!id) { markSkipped(step, 'No ID from CREATE — skipping', start); return }

        // Fetch current state as "before"
        const readUrl = getDetailUrl(actualType, id)
        const readResp = await apiFetch(readUrl, { method: 'GET', headers: { 'Accept': contentType } })
        step.before = readResp.data

        const url = getUpdateUrl(actualType, id)
        let payload = makePayload(step.resourceType, 'update')

        // For controlStreams: merge updated fields into server's current state.
        // OSH requires the 'schema' block on PUT but the GET response does NOT
        // embed the schema inline — it's a separate sub-resource at /schema.
        // Also, OSH crashes (500) if you send CREATE-format field names.
        // Workaround: fetch current state + schema separately, merge into PUT. (S-12)
        if (step.resourceType === 'controlStreams' && readResp.ok && readResp.data) {
          payload = { ...readResp.data, ...payload }
          // Fetch schema sub-resource and inject into payload
          const schemaUrl = `${readUrl}/schema`
          const schemaResp = await apiFetch(schemaUrl, { method: 'GET', headers: { 'Accept': 'application/json' } })
          if (schemaResp.ok && schemaResp.data) {
            payload.schema = schemaResp.data
          }
        }

        const bodyStr = JSON.stringify(payload, null, 2)

        step.request = {
          method: 'PUT', url,
          headers: { 'Content-Type': contentType, 'Accept': contentType },
          body: bodyStr,
        }

        const resp = await apiFetchWithRetry(url, {
          method: 'PUT',
          headers: { 'Content-Type': contentType, 'Accept': contentType },
          body: bodyStr,
        })
        setResponse(step, resp)

        if (!resp.ok) {
          // ControlStream UPDATE: OSH server bug — CommandStreamChangedEvent uses
          // raw deserialized csInfo (missing systemUID) instead of the merged
          // newCsInfo, causing "NPE: UniqueID cannot be null".  (S-13)
          if (step.resourceType === 'controlStreams' && resp.status === 500) {
            markSkipped(step, 'Known server bug: NPE in CommandStreamChangedEvent (S-13)', start)
          } else {
            markFail(step, resp.error || `${resp.status} ${resp.statusText}`, start)
          }
        } else {
          step.after = resp.data || payload
          step.status = 'success'
          const coords = COORDS[step.resourceType]?.update
          if (coords) {
            step.coords = coords
            addMarker(step.resourceType, coords, `smoke-${step.resourceType}`, 'update')
          }
        }
        break
      }

      case 'VERIFY': {
        const id = createdIds[step.resourceType]
        if (!id) { markSkipped(step, 'No ID from CREATE — skipping', start); return }

        const url = getDetailUrl(actualType, id)
        step.request = { method: 'GET', url, headers: { 'Accept': contentType } }

        const resp = await apiFetchWithRetry(url, { method: 'GET', headers: { 'Accept': contentType } })
        setResponse(step, resp)

        if (!resp.ok) {
          markFail(step, resp.error || `${resp.status} ${resp.statusText}`, start)
        } else {
          const updateStep = steps.value.find(
            (s) => s.resourceType === step.resourceType && s.op === 'UPDATE'
          )
          step.before = updateStep?.after || null
          step.after = resp.data
          step.status = 'success'
        }
        break
      }

      case 'DELETE': {
        const id = createdIds[step.resourceType]
        if (!id) { markSkipped(step, 'No ID from CREATE — skipping', start); return }

        const readUrl = getDetailUrl(actualType, id)
        const readResp = await apiFetch(readUrl, { method: 'GET', headers: { 'Accept': contentType } })
        step.before = readResp.data

        const url = getDeleteUrl(actualType, id)
        step.request = { method: 'DELETE', url, headers: {} }

        const resp = await apiFetchWithRetry(url, { method: 'DELETE' })
        setResponse(step, resp)

        if (!resp.ok) {
          markFail(step, resp.error || `${resp.status} ${resp.statusText}`, start)
        } else {
          step.after = null
          step.status = 'success'
          delete createdIds[step.resourceType]
          removeMarker(`smoke-${step.resourceType}`)
        }
        break
      }
    }
  } catch (err: any) {
    step.status = 'fail'
    step.error = err.message || 'Unknown error'
  }

  step.elapsed = performance.now() - start
}

function setResponse(step: Step, resp: any) {
  step.response = {
    status: resp.status,
    statusText: resp.statusText,
    headers: resp.headers,
    body: resp.data ? JSON.stringify(resp.data, null, 2) : (resp.error || ''),
    rawError: resp.error || undefined,
  }
}

function markSkipped(step: Step, msg: string, start: number) {
  step.status = 'skipped'
  step.error = msg
  step.elapsed = performance.now() - start
}

function markFail(step: Step, msg: string, start: number) {
  step.status = 'fail'
  step.error = msg
  step.elapsed = performance.now() - start
}

// ─── Controls ────────────────────────────────────────────

function beginTest() {
  testStarted.value = true
  currentStepIndex.value = 0
  const step = steps.value[0]
  step.status = 'active'
  prepareStepPreview(step)
}

async function executeAndWait() {
  running.value = true
  await executeCurrentStep()
  running.value = false
}

function advanceToNextStep() {
  if (!hasMoreSteps.value) return
  currentStepIndex.value++
  const step = steps.value[currentStepIndex.value]
  step.status = 'active'
  prepareStepPreview(step)
}

function skipCurrentStep() {
  const step = activeStep.value
  if (!step) return
  step.status = 'skipped'
  step.error = 'Manually skipped'
  step.elapsed = 0
}

/** Run all remaining steps automatically without manual clicks. */
async function runAllSteps() {
  if (!testStarted.value) beginTest()
  running.value = true
  while (currentStepIndex.value < steps.value.length) {
    const step = steps.value[currentStepIndex.value]
    if (step.status === 'pending') step.status = 'active'
    if (step.status === 'active') {
      prepareStepPreview(step)
      await executeCurrentStep()
    }
    // Advance to next step
    if (currentStepIndex.value < steps.value.length - 1) {
      currentStepIndex.value++
    } else {
      break
    }
  }
  running.value = false
}

async function abortAndCleanup() {
  cleanupMessage.value = ''
  const idsToDelete = Object.keys(createdIds).filter(k => createdIds[k])
  if (idsToDelete.length === 0) {
    cleanupMessage.value = 'Nothing to clean up \u2014 all resources already deleted'
    setTimeout(() => { cleanupMessage.value = '' }, 4000)
    return
  }
  running.value = true
  cleanupMessage.value = `Deleting ${idsToDelete.length} resource(s)...`
  let deleted = 0
  let failed = 0
  const deleteOrder = ['commands', 'controlStreams', 'observations', 'datastreams', 'subsystems', 'subdeployments', 'samplingFeatures', 'deployments', 'procedures', 'systems']
  for (const type of deleteOrder) {
    const id = createdIds[type]
    if (!id) continue
    try {
      const actual = NESTED_ACTUAL_TYPE[type] || type
      const url = getDeleteUrl(actual, id)
      await apiFetch(url, { method: 'DELETE' })
      delete createdIds[type]
      removeMarker(`smoke-${type}`)
      deleted++
    } catch {
      failed++
    }
  }
  running.value = false
  cleanupMessage.value = failed
    ? `Cleaned up ${deleted} resource(s), ${failed} failed`
    : `Cleaned up ${deleted} resource(s) successfully`
  setTimeout(() => { cleanupMessage.value = '' }, 5000)
}

function resetTest() {
  steps.value = buildSteps()
  currentStepIndex.value = -1
  testStarted.value = false
  running.value = false
  showReport.value = false
  warmUpReady.value = false
  warmUpMessage.value = ''
  for (const key of Object.keys(createdIds)) delete createdIds[key]
  for (const key of Object.keys(createdUids)) delete createdUids[key]
  clearMap()
}

function selectStep(step: Step) {
  // Only allow viewing completed/active steps
  const idx = steps.value.indexOf(step)
  if (idx <= currentStepIndex.value) {
    currentStepIndex.value = idx
  }
  if (step.coords && map) {
    map.getView().animate({ center: fromLonLat(step.coords), duration: 400 })
  }
}

// ─── Formatting helpers ──────────────────────────────────

function opBadgeClass(op: OpType): string {
  return { CREATE: 'op-create', READ: 'op-read', UPDATE: 'op-update', VERIFY: 'op-verify', DELETE: 'op-delete' }[op]
}

function statusIcon(status: StepStatus): string {
  return {
    pending: 'pi pi-circle',
    active: 'pi pi-arrow-right',
    running: 'pi pi-spin pi-spinner',
    success: 'pi pi-check-circle',
    fail: 'pi pi-times-circle',
    skipped: 'pi pi-minus-circle',
  }[status]
}

function statusColor(status: StepStatus): string {
  return {
    pending: '#94a3b8',
    active: '#3b82f6',
    running: '#3b82f6',
    success: '#16a34a',
    fail: '#dc2626',
    skipped: '#f59e0b',
  }[status]
}

function formatMs(ms?: number): string {
  if (ms == null) return ''
  return ms < 1000 ? `${Math.round(ms)}ms` : `${(ms / 1000).toFixed(1)}s`
}

const groupedSteps = computed(() => {
  const groups: { type: string; label: string; steps: Step[] }[] = []
  let current: (typeof groups)[0] | null = null
  for (const step of steps.value) {
    if (!current || current.type !== step.resourceType) {
      current = { type: step.resourceType, label: step.resourceLabel, steps: [] }
      groups.push(current)
    }
    current.steps.push(step)
  }
  return groups
})

